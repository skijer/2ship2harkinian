import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
HEADER = ROOT / "mm/2s2h/GameInteractor/GameInteractor_VanillaBehavior.h"
OUTPUT = ROOT / "mm/2s2h/ModApi/VanillaBehaviorNames.inc"

def generated():
    names = re.findall(r"^\s*(VB_[A-Z0-9_]+)\s*(?:,|=)", HEADER.read_text(encoding="utf-8"), re.MULTILINE)
    if not names or len(names) != len(set(names)):
        raise ValueError("Invalid vanilla behavior enum")
    return "// Generated by mod-sdk/tools/sync_behavior_names.py.\n" + "".join(
        f"UNBOUND_BEHAVIOR({name})\n" for name in names)

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Synchronize named vanilla behavior dispatch with the host enum")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = generated()
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != text:
            raise SystemExit("VanillaBehaviorNames.inc is stale; run sync_behavior_names.py")
    else:
        OUTPUT.write_text(text, encoding="utf-8")
